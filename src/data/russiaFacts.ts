export interface TeaCombinationInfo {
  title: string;
  meaning: string;
  tasteProfile: string;
  resembles: string;
  tradition: string;
}

export function getTeaCombinationMeaning(selectedIds: string[]): TeaCombinationInfo {
  const set = new Set(selectedIds);

  // 1. No ingredients selected
  if (set.size === 0) {
    return {
      title: 'Классический крепкий русский чай',
      meaning: '«Основа русского дома, чистота мысли и вековая традиция»',
      tasteProfile: 'Глубокий, терпкий, смолисто-бархатный вкус с благородной древесной горчинкой и чистым согревающим послевкусием.',
      resembles: 'Напоминает свежезаваренный утренний чай у самовара в тихой деревянной избе, когда за окном прохладно.',
      tradition: 'Черный байховый чай без добавок — фундамент любого русского застолья. Его заваривали в заварнике («заварка») и разбавляли крутым кипятком из краника самовара. Выберите добавки выше, чтобы создать свой авторский купаж!',
    };
  }

  // 2. Specific 4-ingredient combos: Thyme + Lemon + Honey + Mint (User's specific case!)
  if (set.has('thyme') && set.has('lemon') && set.has('honey') && set.has('mint')) {
    return {
      title: '«Великий богатырский сбор 4 стихий» 🛡️',
      meaning: '«Несокрушимое здоровье, ясность ума и гармония четырёх стихий»',
      tasteProfile: 'Многослойный шедевр: начинается с нежной медовой сладости, взрывается искрящейся лимонной кислинкой, а затем раскрывается мягким ментоловым холодком с благородной пряной терпкостью чабреца.',
      resembles: 'Напоминает знаменитый старинный русский сбитень и целебный горный чай, который пили после долгого перехода по тайге.',
      tradition: 'Считалось, что такой настой ставит на ноги даже самого усталого путника с любого мороза, укрепляет иммунитет и дарит богатырскую силу духа.',
    };
  }

  // Thyme + Berries + Honey + Pryanik (Tsar's Feast)
  if (set.has('thyme') && set.has('berries') && set.has('honey') && set.has('pryanik')) {
    return {
      title: '«Царское купеческое чаепитие» 👑',
      meaning: '«Символ изобилия, душевного раздолья и щедрого гостеприимства»',
      tasteProfile: 'Очень сладкий, ягодно-медовый и пряный вкус с тонким ароматом корицы, яблочного повидла и душистых степных трав.',
      resembles: 'Напоминает праздничное застолье в купеческом тереме с самоваром на 10 литров и горой праздничных угощений.',
      tradition: 'Купцы пили такой чай часами «до седьмого пота», наливая его в широкие блюдца, чтобы не обжечься, и смакуя каждый глоток за неспешной беседой.',
    };
  }

  // Lemon + Honey + Mint
  if (set.has('lemon') && set.has('honey') && set.has('mint') && !set.has('thyme')) {
    return {
      title: '«Солнечный родник» ☀️',
      meaning: '«Чистая радость, легкость на сердце и искренняя дружба»',
      tasteProfile: 'Идеальный баланс: цитрусово-сладкий с бодрящей кислинкой лимона и леденящей мятной свежестью. Не приторный, удивительно мягкий.',
      resembles: 'Напоминает натуральный домашний медово-лимонный лимонад, поданный в горячем согревающем виде.',
      tradition: 'Этот напиток готовили в русских усадьбах ранней весной, чтобы прогнать зимнюю усталость и зарядиться солнечной энергией.',
    };
  }

  // Thyme + Mint + Honey
  if (set.has('thyme') && set.has('mint') && set.has('honey') && !set.has('lemon')) {
    return {
      title: '«Монастырское умиротворение» 🕊️',
      meaning: '«Сердечный покой, душевное равновесие и неспешные ночные разговоры»',
      tasteProfile: 'Бархатистый, травянисто-медовый вкус с приятным ментоловым холодком и глубокой степной терпкостью.',
      resembles: 'Напоминает настой с альпийских лугов или старинный травяной чай, заваренный на ключевой родниковой воде.',
      tradition: 'Травяной настой мяты и чабреца с липовым мёдом успокаивает мысли, снимает напряжение дня и располагает к глубоким философским беседам.',
    };
  }

  // Thyme + Berries (Taiga)
  if (set.has('thyme') && set.has('berries') && !set.has('honey') && !set.has('pryanik')) {
    return {
      title: '«Таёжный сибирский сбор» 🌲',
      meaning: '«Стойкость духа, здоровье и свежесть глухих лесных троп»',
      tasteProfile: 'Свежий, терпко-кислый вкус с выраженным ягодным ароматом черной смородины и смолистым шлейфом чабреца. Без лишней сладости.',
      resembles: 'Напоминает чай сибирских охотников у костра в окружении сосен и кедров.',
      tradition: 'Таёжники сушили молодые листья смородины и цветы чабреца на зиму: этот чай наполнял витаминами и спасал от цинги в суровые морозы.',
    };
  }

  // Lemon + Honey
  if (set.has('lemon') && set.has('honey') && set.size === 2) {
    return {
      title: '«Русский зимний оберег» ❄️',
      meaning: '«Тепло заботы, верное исцеление и защита от любой хандры»',
      tasteProfile: 'Сладкий с приятной бодрящей кислинкой. Мёд смягчает резкость лимона, создавая густой золотистый напиток.',
      resembles: 'Напоминает чай, который заботливая мама или бабушка заваривает в детстве, укутывая тёплым пледом.',
      tradition: 'В каждой русской семье знают: кружка горячего чая с лимоном и ложкой душистого мёда — лучшее средство от простуды и любой тоски.',
    };
  }

  // Mint + Thyme
  if (set.has('mint') && set.has('thyme') && set.size === 2) {
    return {
      title: '«Степной ветер и ясный ум» 💻',
      meaning: '«Ясность мыслей, концентрация и вдохновение для смелых идей»',
      tasteProfile: 'Пряно-освежающий, слегка терпкий травяной вкус с долгим прохладным ментоловым послевкусием без сахара.',
      resembles: 'Напоминает утреннюю росу на степных травах на рассвете.',
      tradition: 'Чабрец с мятой бодрит лучше кофе, но без учащенного пульса — идеальный выбор для студентов, пишущих код или читающих новеллы до утра.',
    };
  }

  // Pryanik + Tea
  if (set.has('pryanik')) {
    return {
      title: '«Чай вприкуску с Тульским пряником» 🍪',
      meaning: '«Сладость крепкой дружбы и дань русским мастерам»',
      tasteProfile: 'Насыщенно сладкий, медово-пряный с легкой кислинкой яблочного повидла и ароматом корицы и кардамона.',
      resembles: 'Напоминает ярмарочные гулянья на Руси, запах свежей выпечки и праздник.',
      tradition: 'Пряник никогда не бросали в чай! Его отламывали маленькими кусочками и смаковали «вприкуску» с горячим напитком.',
    };
  }

  // Berries only or Berries with Mint
  if (set.has('berries')) {
    return {
      title: '«Лесная смородиновая поляна» 🫐',
      meaning: '«Яркая радость, воспоминания о лете и детском счастье»',
      tasteProfile: 'Сочный кисло-сладкий фруктовый вкус с насыщенным рубиновым цветом и лёгкой танинной терпкостью ягодной кожицы.',
      resembles: 'Напоминает бабушкино варенье-пятиминутку, разведённое в горячем ключевом чае.',
      tradition: 'Смородиновый чай — любимый дачный напиток в России, его пили летними вечерами на террасе под звуки сверчков.',
    };
  }

  // Lemon only
  if (set.has('lemon') && set.size === 1) {
    return {
      title: '«Чай по-русски с лимоном» 🍋',
      meaning: '«Бодрость духа, острота ума и открытость миру»',
      tasteProfile: 'Яркий, выразительно кислый с приятной цитрусовой горчинкой от цедры и освежающим ароматом.',
      resembles: 'Напоминает классический дорожный чай в подстаканнике в купе поезда Транссибирской магистрали.',
      tradition: 'В XIX веке в Европе чай с долькой лимона так и называли — «Thé à la russe» (чай по-русски), ведь именно в России придумали добавлять цитрус в горячий чай на почтовых станциях.',
    };
  }

  // Mint only
  if (set.has('mint') && set.size === 1) {
    return {
      title: '«Мятная прохлада» 🌿',
      meaning: '«Тишина, внутренний покой и гармония с собой»',
      tasteProfile: 'Легкий, освежающий, прохладно-бархатный с нежным ароматом перечной мяты.',
      resembles: 'Напоминает вечерний ветерок в цветущем саду.',
      tradition: 'Мятный чай пили перед сном, чтобы прогнать тревожные мысли и спать крепким богатырским сном.',
    };
  }

  // Honey only
  if (set.has('honey') && set.size === 1) {
    return {
      title: '«Липовый медовый взвар» 🍯',
      meaning: '«Доброта, нежность и согревающее гостеприимство»',
      tasteProfile: 'Мягкий, обволакивающий, тягуче-сладкий с цветочным медовым ароматом цветущей липы.',
      resembles: 'Напоминает тепло русской печи и солнечный летний полдень на пасеке.',
      tradition: 'Липовый мёд на Руси почитался за «белое золото». Ложку мёда клали в рот и не спеша запивали горячим чаем.',
    };
  }

  // Thyme only
  if (set.has('thyme') && set.size === 1) {
    return {
      title: '«Богородская трава (Чабрец)» 🌱',
      meaning: '«Сила земли, защита очага и мужество»',
      tasteProfile: 'Пряный, терпкий, слегка смолистый с благородной травяной горчинкой.',
      resembles: 'Напоминает просторы донских и поволжских степей в разгар июля.',
      tradition: 'Чабрец на Руси называли «богородской травой» и верили, что его пряный аромат очищает дом от дурных вестей и дарует здоровье.',
    };
  }

  // Dynamic fallback for any other combination
  const hasSweet = set.has('honey') || set.has('pryanik');
  const hasSour = set.has('lemon') || set.has('berries');
  const hasHerbal = set.has('thyme') || set.has('mint');

  let profile = '';
  if (hasSweet && hasSour && hasHerbal) {
    profile = 'Изысканный контрастный вкус: сочная кислинка фруктов плавно переходит в медовую сладость и оставляет долгое свежее травяное послевкусие.';
  } else if (hasSweet && hasSour) {
    profile = 'Гармоничный кисло-сладкий букет с ярким ягодно-цитрусовым шлейфом.';
  } else if (hasHerbal && hasSour) {
    profile = 'Тонизирующий терпко-кислый сбор с насыщенными травяными нотками, проясняющими сознание.';
  } else if (hasSweet && hasHerbal) {
    profile = 'Мягкий, обволакивающий сладковатый травяной настой, идеальный для уютного отдыха.';
  } else {
    profile = 'Неповторимый авторский сбор с гармоничным вкусом традиционного русского чаепития.';
  }

  return {
    title: '«Авторский купаж МФМ 2026» ✨',
    meaning: '«Уникальный вкус нашей дружбы, рождённый в этот момент»',
    tasteProfile: profile,
    resembles: 'Напоминает душевные посиделки с новыми друзьями у самовара на международном фестивале.',
    tradition: 'В России каждый хозяин добавлял в заварник травы и ягоды по зову сердца. Твой рецепт уникален, как и наша встреча!',
  };
}

